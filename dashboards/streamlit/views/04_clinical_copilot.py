"""SBAR brief: clinical support for medication substitution.

UX intent
---------
This is the app's cognitive surface: a compact form on the left, a generated
brief on the right. Everything is structured around SBAR (Situation /
Background / Assessment / Recommendation): the standard clinical transmission
format taught in nursing schools and used worldwide.

Why ``st.write_stream``
------------------------
A pharmacist is not going to wait 8 seconds to read 4 paragraphs at once. The
streaming lets them start reading the *Situation* while the *Assessment* is
still being generated, cutting the perceived latency roughly in half.

Language: this surface is business-first. The “how it was calculated” lives in
an expander called “How does this work?”, not in the reading surface.
"""
from __future__ import annotations

import streamlit as st
from lib import components as C
from lib import llm_logic as L
from lib.data import M
from lib.settings import get_settings
from lib.theme import TOK

# ---------------------------------------------------------------------------
# Page header
# ---------------------------------------------------------------------------
C.page_header(
    eyebrow="Clinical support",
    icon="file-text",
    title="SBAR brief",
    subtitle=(
        "A substitution brief ready to send, backed by clinical sources. "
        "Pharmacist validation is mandatory before transmission."
    ),
    tip=(
        "The brief is generated by a local language model (no data leaves the hospital), "
        "supported by indexed documents. These documents are not verified Indian clinical guidance."
    ),
)


# ---------------------------------------------------------------------------
# Form column / output column
# ---------------------------------------------------------------------------
form_col, output_col = st.columns([1, 1.6], gap="large")

with form_col:
    C.section_header("Context", icon="search",
                     subtitle="sources found automatically")

    # Default medication from a previous page (fridge or forecast)
    default_drug = st.session_state.get("copilot_drug", "Influenza vaccine (inactivated)|J07BB02")
    if isinstance(default_drug, str) and "|" in default_drug:
        default_drug_name, default_atc = default_drug.split("|", 1)
    else:
        default_drug_name, default_atc = default_drug, ""

    with st.form("copilot_form", border=False):
        choices = [f"{d[0]}|{d[1]}" for d in M.DRUGS]
        try:
            idx = next(i for i, c in enumerate(choices)
                       if c.startswith(default_drug_name))
        except StopIteration:
            idx = 0
        drug = st.selectbox(
            "Medication in question",
            choices,
            index=idx,
            format_func=lambda s: f"{s.split(chr(124))[0]} ({s.split(chr(124))[1]})",
        )

        ctx = st.selectbox(
            "Clinical context",
            [
                "Hospitalization",
                "Outpatient / consultation",
                "Emergency department",
                "Pediatrics",
                "Geriatrics",
            ],
            index=0,
        )

        horizon = st.selectbox("Forecast horizon",
                               ["7 days", "14 days", "30 days"], index=1)

        nurse_note = st.text_area(
            "Nurse note (optional)",
            placeholder="Example: patient allergic to peanuts, titration schedule in progress…",
            height=110,
        )

        submitted = st.form_submit_button("Generate SBAR brief", type="primary",
                                          use_container_width=True)

    # Side panel: how this works ----------------------------------------------
    _s = get_settings()
    _llm_line = (
        f"3. The local model ({_s.ollama_model}) drafts the brief line by line, citing its sources. "
        "*(Illustrative brief; the telemetry stream is simulated.)*"
        if _s.use_llm_mock else
        f"3. The local model ({_s.ollama_model}, via Ollama) drafts the brief line by line, citing its sources."
    )
    with st.expander("How does this work?", expanded=False):
        st.markdown(
            f"""
            **The brief path**

            1. Your context becomes a structured SBAR prompt.
            2. The indexed documents are queried:
               3 to 5 relevant excerpts are retrieved, along with their score.
            {_llm_line}
            4. The pharmacist reads, checks the 4 validation criteria, then
               sends the brief to the prescriber. The nurse performs the 5-right
               bedside check.

            **Why SBAR?**
            A structured clinical handoff format. Any local use must follow
            institution-approved procedures and applicable Indian requirements.
            """
        )

# Output column ---------------------------------------------------------------
with output_col:
    if not submitted and "last_brief" not in st.session_state:
        # Empty state: no brief generated yet
        C.callout(
            "<strong>No brief generated yet.</strong> Fill in the form on the left and click "
            "<em>Generate SBAR brief</em>. The brief is written line by line: you can start reading from the first line.",
        )
        st.markdown(
            f"""
            <div style="margin-top:1rem;display:grid;grid-template-columns:repeat(2,1fr);
                        gap:.5rem;font-size:.85rem;color:{TOK.text_secondary};">
              <div><b>S</b>ituation: what triggered the alert</div>
              <div><b>B</b>ackground: molecule, shortage signal, context</div>
              <div><b>A</b>ssessment: clinical risk + justification</div>
              <div><b>R</b>ecommendation: proposed decision</div>
            </div>
            """,
            unsafe_allow_html=True,
        )
    else:
        # If this is a fresh submission, build a brief; otherwise re-render the last one.
        if submitted:
            drug_name, _, atc = drug.partition("|")
            brief = L.build_brief(drug_name)
            st.session_state["last_brief"] = brief
            st.session_state["last_form"] = {
                "drug": drug_name, "atc": atc, "ctx": ctx,
                "horizon": horizon, "nurse_note": nurse_note,
            }

        brief = st.session_state["last_brief"]
        form = st.session_state["last_form"]

        # Brief header card ---------------------------------------------------
        st.markdown(
            f"""
            <div style="background:#FFFFFF;border:1px solid var(--ms-border);
                        border-radius:var(--ms-radius-lg);padding:1rem 1.15rem;
                        box-shadow:var(--ms-shadow-sm);margin-bottom:1rem;">
              <div style="display:flex;justify-content:space-between;
                          align-items:flex-start;gap:.5rem;">
                <div>
                  <div style="font-size:.7rem;font-weight:700;color:var(--ms-brand);
                              letter-spacing:.12em;text-transform:uppercase;">
                    SBAR substitution brief
                  </div>
                  <div style="font-size:1.05rem;font-weight:700;color:var(--ms-text);
                              margin-top:.15rem;">
                    {form['drug']} <span style="font-family:{TOK.font_mono};font-size:.78rem;
                    color:var(--ms-text-2);font-weight:500;
                    background:var(--ms-bg-muted);padding:1px 6px;border-radius:5px;
                    margin-left:.35rem;">{form['atc']}</span>
                  </div>
                  <div style="color:var(--ms-text-2);font-size:.85rem;margin-top:.15rem;">
                    Context: <b>{form['ctx']}</b>,
                    horizon: <b>{form['horizon']}</b>
                  </div>
                </div>
                <div>
                  <span class="ms-pill info"><span class="dot"></span>{brief.model}</span>
                </div>
              </div>
            </div>
            """,
            unsafe_allow_html=True,
        )

        # Streamed text ------------------------------------------------------
        if submitted:
            with st.container(border=False):
                st.write_stream(L.stream_sbar_text(brief, tps=45))
        else:
            # Re-render the last brief without re-streaming
            for tag, body in [
                ("Situation",      brief.situation),
                ("Background",     brief.background),
                ("Assessment",     brief.assessment),
                ("Recommendation", brief.recommendation),
            ]:
                st.markdown(f"\n**{tag.upper()}**  \n{body}")

        # Alternatives + redistribution + citations
        st.markdown("---")

        a_tab, r_tab, c_tab = st.tabs([
            f"Alternatives ({len(brief.alternatives)})",
            f"Redistribution ({len(brief.redistribution)})",
            f"Sources ({len(brief.citations)})",
        ])

        with a_tab:
            st.caption("Equivalent-class substitutes: proposed automatically and subject to pharmacist validation.")
            for a in brief.alternatives:
                C.alternative_card(a.name, a.atc_code, a.dosing, a.caveats)

        with r_tab:
            st.caption("Network sites with usable surplus stock, ranked by distance.")
            import pandas as pd
            rdf = pd.DataFrame([{
                "Site": r.site_name,
                "Available stock": f"{r.stock} u.",
                "Distance": f"{r.distance_km} km",
            } for r in brief.redistribution])
            st.dataframe(rdf, hide_index=True, use_container_width=True)

        with c_tab:
            st.caption("Excerpts are from example documents and are not verified Indian clinical guidance.")
            for c in brief.citations:
                score = f"score {c.score:.2f}" if c.score else ""
                st.markdown(
                    f"""
                    <div style="background:#FFFFFF;border:1px solid var(--ms-border);
                                border-left:3px solid var(--ms-brand);
                                border-radius:var(--ms-radius-md);padding:.7rem .9rem;
                                margin-bottom:.5rem;">
                      <div style="font-weight:600;color:var(--ms-text);font-size:.875rem;
                                  display:flex;justify-content:space-between;align-items:baseline;">
                        <span>{c.document}, p.{c.page}</span>
                        <span style="font-family:{TOK.font_mono};color:var(--ms-brand);
                                     font-size:.72rem;font-weight:600;">{score}</span>
                      </div>
                      <div style="color:var(--ms-text-2);font-size:.85rem;
                                  font-style:italic;margin-top:.2rem;">
                        « {c.quote} »
                      </div>
                    </div>
                    """,
                    unsafe_allow_html=True,
                )

        # Action: go to validation ---------------------------------------------
        st.markdown("---")
        C.callout(
            "<strong>This brief is not final as-is.</strong> It must be validated by the pharmacist "
            "(4 checks) and then verified by the nurse at the bedside (5-right rule).",
            variant="alert",
        )
        if st.button("Proceed to pharmacist validation",
                     type="primary", use_container_width=True):
            st.switch_page("views/05_validation.py")
